"""DFT cell harness — drive PeriodicDFTAgent across the systems tagged
``dft``, submit per-cell VASP relaxations, and score the converged
results against the reference observables in ``systems.py``.

Three phases, mirroring validation/run_panel.py:

  generate   — write POSCAR (sorted by element) + INCAR / KPOINTS
               (generated by PeriodicDFTAgent in c_bare_goal mode) +
               per-cell submit.sbatch.  Local only.
  submit     — sbatch every cell's submit.sbatch; record job IDs.
  collect    — read CONTCAR, compute observable, score.
  all        — generate + submit (collect runs after VASP finishes).

The companion ``benchmark/submit_test_dft.sbatch`` is the cluster driver
that runs ``generate`` + ``submit`` from a GPU-shared queue slot (so the
LLM gen step has accelerator availability if needed).

Scope notes (Monday cut):
  * Bulks are scored on the cubic lattice constant `a` (cellpar[0])
    vs ``expected["a"]``.  Pass band: |Δ| ≤ 2.5 %.
  * Surface systems are submitted but scored only on "did VASP converge";
    adsorption-energy scoring needs a separate isolated-fragment workflow
    and is deferred.
  * Hexagonal / non-cubic bulks (e.g. LiCoO2) are submitted but reported
    with both ``a`` and ``c``; pass condition checks both within band.

Examples
--------
    python -m benchmark.runner test_dft --phase generate --system fe_bcc
    python -m benchmark.runner test_dft --phase generate          # all bulks
    python -m benchmark.runner test_dft --phase submit            # sbatch them
    python -m benchmark.runner test_dft --phase collect           # score
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import traceback
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from ._score import CaseResult, RunnerManifest, write_manifest, write_summary_md
from .systems import BenchmarkSystem, get_system, systems_for_agent


_PASS_BAND_PCT = 2.5          # |Δa / a_exp| ≤ this counts as "pass"
_OUT_DEFAULT = "benchmark/outputs/test_dft"


# ──────────────────────────────────────────────────────────────────
#  Generate phase
# ──────────────────────────────────────────────────────────────────

def _generate_one(system: BenchmarkSystem,
                  rundir: str,
                  api_key: Optional[str],
                  base_url: Optional[str],
                  model_name: str) -> Dict[str, Any]:
    """Generate POSCAR + VASP inputs + submit.sbatch for one system.
    Returns a record that goes into manifest['cells'][<name>]."""
    from scilink.agents.sim_agents.periodic_dft_agent import PeriodicDFTAgent
    from ._vasp import write_poscar, write_per_cell_sbatch

    os.makedirs(rundir, exist_ok=True)

    # Build the structure and write POSCAR.  TODO-builder systems raise
    # NotImplementedError here, which the caller surfaces.
    atoms = system.build()
    poscar = os.path.join(rundir, "POSCAR")
    write_poscar(atoms, poscar)

    # Bare-goal: agent must classify the material and infer all params.
    goal = system.goal(level="bare")

    agent = PeriodicDFTAgent(api_key=api_key, base_url=base_url,
                             model_name=model_name)
    result = agent.generate_inputs(
        structure_file=poscar,
        request=goal,
        software="vasp",
    )
    if result.get("status") != "success":
        return {"status": "error",
                "message": result.get("message", "generate_inputs failed"),
                "rundir": rundir}
    agent.save_inputs(result, output_dir=rundir)

    # save_inputs may echo an unsorted POSCAR — re-write ours so the
    # canonical structure is unambiguous.
    write_poscar(atoms, poscar)

    # Per-cell sbatch.  Unique element list, order matches POSCAR (sorted).
    unique_elements = sorted(set(atoms.get_chemical_symbols()))
    write_per_cell_sbatch(rundir,
                          job_name=f"bench_{system.name}",
                          elements=unique_elements,
                          time="00:30:00" if system.kind == "bulk" else "02:00:00",
                          ntasks_per_node=16)

    return {"status": "generated",
            "rundir": rundir,
            "elements": unique_elements,
            "kind": system.kind,
            "expected": dict(system.expected),
            "goal_level": "bare",
            "input_files": sorted(result.get("input_files", {})),
            "notes": result.get("notes", ""),
            "run_cmd": "sbatch submit.sbatch"}


# ──────────────────────────────────────────────────────────────────
#  Submit phase
# ──────────────────────────────────────────────────────────────────

def _sbatch(rundir: str) -> Tuple[bool, str]:
    """Submit submit.sbatch from inside rundir.  Returns (ok, job_id_or_err)."""
    script = os.path.join(rundir, "submit.sbatch")
    if not os.path.isfile(script):
        return False, f"no submit.sbatch in {rundir}"
    try:
        out = subprocess.check_output(
            ["sbatch", "--parsable", "submit.sbatch"],
            cwd=rundir, stderr=subprocess.STDOUT, text=True,
        )
        return True, out.strip()
    except FileNotFoundError:
        return False, "sbatch not in PATH (are we on a login node?)"
    except subprocess.CalledProcessError as exc:
        return False, f"sbatch failed: {exc.output.strip()}"


# ──────────────────────────────────────────────────────────────────
#  Collect phase
# ──────────────────────────────────────────────────────────────────

def _score_one(system: BenchmarkSystem,
               cell: Dict[str, Any]) -> CaseResult:
    """Read CONTCAR / OUTCAR for ``cell`` and score against expected."""
    from ._vasp import read_relaxed_atoms, lattice_a, final_energy

    rundir = cell["rundir"]
    expected = dict(system.expected)

    try:
        atoms = read_relaxed_atoms(rundir)
    except Exception as exc:
        return CaseResult(
            id=system.name,
            expected=expected,
            actual={"rundir": rundir, "error": str(exc)},
            score=0.0,
            passed=False,
            notes="VASP did not produce a relaxed structure (CONTCAR missing/empty)",
        )

    energy = final_energy(rundir)

    if system.kind == "surface":
        # Adsorption-energy scoring needs isolated fragments; defer.
        # Score 0.5 just for converging.  Pass = false until we wire
        # the full workflow.
        return CaseResult(
            id=system.name,
            expected=expected,
            actual={"rundir": rundir,
                    "final_energy_eV": energy,
                    "note": "surface — convergence-only scoring this round"},
            score=0.5,
            passed=False,
            notes="surface scoring deferred (need isolated-fragment refs)",
        )

    # Bulk-ish systems: score the dominant lattice parameter.
    a_actual = lattice_a(atoms)
    a_expected = expected.get("a")
    if a_expected is None:
        return CaseResult(
            id=system.name,
            expected=expected,
            actual={"rundir": rundir, "a_actual": a_actual,
                    "final_energy_eV": energy},
            score=0.5,
            passed=False,
            notes="no `a` in expected — can't score lattice",
        )
    dpct = 100.0 * (a_actual - a_expected) / a_expected
    passed = abs(dpct) <= _PASS_BAND_PCT
    return CaseResult(
        id=system.name,
        expected={"a": a_expected, **expected},
        actual={"rundir": rundir,
                "a_actual": round(a_actual, 4),
                "delta_pct": round(dpct, 3),
                "final_energy_eV": energy},
        score=1.0 if passed else max(0.0, 1.0 - abs(dpct) / 10.0),
        passed=passed,
        notes=f"|Δ| = {abs(dpct):.2f} % (band ±{_PASS_BAND_PCT} %)",
    )


# ──────────────────────────────────────────────────────────────────
#  Manifest persistence (so the three phases stitch together)
# ──────────────────────────────────────────────────────────────────

def _manifest_path(out_dir: str) -> str:
    return os.path.join(out_dir, "manifest.json")


def _load_state(out_dir: str) -> Dict[str, Any]:
    p = _manifest_path(out_dir)
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return {"runner": "test_dft", "mode": "cluster",
            "n_cases": 0, "passed": 0, "failed": 0,
            "metrics": {}, "cases": [], "cells": {}}


def _save_state(out_dir: str, state: Dict[str, Any]) -> None:
    os.makedirs(out_dir, exist_ok=True)
    with open(_manifest_path(out_dir), "w") as f:
        json.dump(state, f, indent=2)


# ──────────────────────────────────────────────────────────────────
#  Main
# ──────────────────────────────────────────────────────────────────

def _selected_systems(args) -> List[BenchmarkSystem]:
    systems = systems_for_agent("dft")
    if args.system:
        systems = [get_system(args.system)]
    if args.skip_surfaces:
        systems = [s for s in systems if s.kind != "surface"]
    if args.limit:
        systems = systems[: args.limit]
    return systems


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="test_dft", description=__doc__)
    parser.add_argument("--phase", choices=("generate", "submit", "collect", "all"),
                        default="all")
    parser.add_argument("--model",    default="claude-sonnet-4-5")
    parser.add_argument("--api-key",  default=None)
    parser.add_argument("--base-url", default=None)
    parser.add_argument("--system",   default=None,
                        help="run only this system (slug)")
    parser.add_argument("--limit",    type=int, default=None)
    parser.add_argument("--skip-surfaces", action="store_true",
                        help="omit surface systems (default keeps them; "
                             "they score 0.5 on convergence-only)")
    parser.add_argument("--out-dir",  default=_OUT_DEFAULT)
    parser.add_argument("--dry-run",  action="store_true",
                        help="describe what would run; no LLM, no sbatch")
    args = parser.parse_args(argv)

    systems = _selected_systems(args)
    print(f"test_dft :: phase={args.phase}  n_systems={len(systems)}  "
          f"model={args.model}")

    if args.dry_run:
        for s in systems:
            print(f"  [{s.kind:<8}] {s.name:<22} elements={s.elements}  "
                  f"expected={s.expected}")
        return 0

    state = _load_state(args.out_dir)
    do = {"all": {"generate", "submit", "collect"}}.get(
        args.phase, {args.phase})

    api_key = args.api_key or os.environ.get("SCILINK_API_KEY")
    base_url = args.base_url or os.environ.get("SCILINK_BASE_URL")

    # ── generate ─────────────────────────────────────────────────
    if "generate" in do:
        if not api_key:
            print("!! no SCILINK_API_KEY — generate needs LLM access",
                  file=sys.stderr)
            return 2
        for s in systems:
            rundir = os.path.join(args.out_dir, s.name)
            print(f"[generate] {s.name}")
            try:
                cell = _generate_one(s, rundir, api_key, base_url, args.model)
            except NotImplementedError as exc:
                print(f"    skipped (TODO builder): {exc}")
                cell = {"status": "skipped",
                        "rundir": rundir,
                        "message": f"TODO builder: {exc}"}
            except Exception as exc:
                print(f"    !! {exc!r}")
                traceback.print_exc()
                cell = {"status": "error", "rundir": rundir,
                        "message": repr(exc)}
            state["cells"][s.name] = cell
        _save_state(args.out_dir, state)

    # ── submit ───────────────────────────────────────────────────
    if "submit" in do:
        for s in systems:
            cell = state["cells"].get(s.name) or {}
            if cell.get("status") != "generated":
                print(f"[submit] {s.name}: skipping (status="
                      f"{cell.get('status', 'missing')})")
                continue
            ok, msg = _sbatch(cell["rundir"])
            if ok:
                cell["job_id"] = msg
                cell["status"] = "submitted"
                print(f"[submit] {s.name} → job {msg}")
            else:
                cell["submit_error"] = msg
                print(f"[submit] {s.name}: FAILED — {msg}")
            state["cells"][s.name] = cell
        _save_state(args.out_dir, state)

    # ── collect ──────────────────────────────────────────────────
    if "collect" in do:
        manifest = RunnerManifest(runner="test_dft", mode="cluster")
        for s in systems:
            cell = state["cells"].get(s.name)
            if not cell or cell.get("status") in ("skipped", "error"):
                manifest.append(CaseResult(
                    id=s.name,
                    expected=dict(s.expected),
                    actual=cell or {"status": "missing"},
                    score=0.0, passed=False,
                    notes=cell.get("message", "no cell record") if cell else "",
                ))
                continue
            case = _score_one(s, cell)
            manifest.append(case)
            flag = "✓" if case.passed else "✗"
            print(f"[collect] {flag} {s.name}: {case.notes}")

        if manifest.cases:
            manifest.metrics = {
                "pass_rate":  manifest.passed / max(1, manifest.n_cases),
                "mean_score": sum(c.score for c in manifest.cases)
                              / max(1, manifest.n_cases),
            }
        write_manifest(args.out_dir, manifest)
        write_summary_md(args.out_dir, manifest)
        print(f"\nwrote {args.out_dir}/manifest.json (+summary.md)")
        if manifest.metrics:
            print(f"pass rate: {manifest.metrics['pass_rate']:.2f}    "
                  f"mean score: {manifest.metrics['mean_score']:.2f}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
